constexpr qint64 ManifestLimit = 16LL * 1024 * 1024;
constexpr qint64 MemberLimit = 256LL * 1024 * 1024;
constexpr qint64 ArchiveLimit = 1024LL * 1024 * 1024;
constexpr mz_uint EntryLimit = 4096;
struct alignas(std::max_align_t) Allocation {
    std::size_t size;
};
void* allocate(void* opaque, std::size_t items, std::size_t size) noexcept {
    auto budget = static_cast<MemoryBudget*>(opaque);
    if (size && items > (std::numeric_limits<std::size_t>::max() - sizeof(Allocation)) / size)
        return nullptr;
    const auto bytes = items * size + sizeof(Allocation);
    try {
        budget->reserve(bytes);
    } catch (...) {
        return nullptr;
    }
    auto block = static_cast<Allocation*>(std::malloc(bytes));
    if (!block) {
        budget->release(bytes);
        return nullptr;
    }
    block->size = bytes;
    return block + 1;
}
void release(void* opaque, void* ptr) noexcept {
    if (!ptr)
        return;
    auto block = static_cast<Allocation*>(ptr) - 1;
    static_cast<MemoryBudget*>(opaque)->release(block->size);
    std::free(block);
}
void* reallocate(void* opaque, void* old, std::size_t items, std::size_t size) noexcept {
    auto next = allocate(opaque, items, size);
    if (!next)
        return nullptr;
    if (old) {
        std::memcpy(next, old,
                    std::min(items * size, (static_cast<Allocation*>(old) - 1)->size - sizeof(Allocation)));
        release(opaque, old);
    }
    return next;
}
size_t read(void* opaque, mz_uint64 offset, void* buffer, size_t count) {
    auto file = static_cast<QIODevice*>(opaque);
    if (offset > static_cast<mz_uint64>(std::numeric_limits<qint64>::max()) ||
        !file->seek(static_cast<qint64>(offset)))
        return 0;
    auto n = file->read(static_cast<char*>(buffer), static_cast<qint64>(count));
    return n < 0 ? 0 : static_cast<size_t>(n);
}
size_t write(void* opaque, mz_uint64 offset, const void* buffer, size_t count) {
    auto file = static_cast<QIODevice*>(opaque);
    if (offset > static_cast<mz_uint64>(std::numeric_limits<qint64>::max()) ||
        !file->seek(static_cast<qint64>(offset)))
        return 0;
    auto n = file->write(static_cast<const char*>(buffer), static_cast<qint64>(count));
    return n < 0 ? 0 : static_cast<size_t>(n);
}
struct Archive {
    mz_zip_archive zip{};
    bool writing{};
    Archive(QIODevice& file, const std::shared_ptr<MemoryBudget>& budget, bool writer) : writing(writer) {
        zip.m_pIO_opaque = &file;
        zip.m_pAlloc_opaque = budget.get();
        zip.m_pAlloc = allocate;
        zip.m_pRealloc = reallocate;
        zip.m_pFree = release;
        zip.m_pRead = read;
        zip.m_pWrite = write;
    }
    ~Archive() {
        if (writing)
            mz_zip_writer_end(&zip);
        else
            mz_zip_reader_end(&zip);
    }
    Archive(const Archive&) = delete;
    Archive& operator=(const Archive&) = delete;
    void add(const QByteArray& name, const QByteArray& data, bool compress = true) {
        if (!mz_zip_writer_add_mem(&zip, name.constData(), data.constData(),
                                   static_cast<std::size_t>(data.size()), compress ? 6 : 0))
            throw std::runtime_error("Could not write archive entry");
    }
};
QByteArray extract(Archive& archive, const QByteArray& name, qint64 maximum,
                   const std::shared_ptr<MemoryBudget>& budget) {
    const auto index = mz_zip_reader_locate_file(&archive.zip, name.constData(), nullptr, 0);
    mz_zip_archive_file_stat stat{};
    if (index < 0 || !mz_zip_reader_file_stat(&archive.zip, static_cast<mz_uint>(index), &stat) ||
        stat.m_uncomp_size > static_cast<mz_uint64>(maximum))
        throw std::invalid_argument("Missing or oversized archive entry");
    Reservation scratch(budget, static_cast<std::size_t>(stat.m_uncomp_size));
    QByteArray data(static_cast<qsizetype>(stat.m_uncomp_size), Qt::Uninitialized);
    if (!mz_zip_reader_extract_to_mem(&archive.zip, static_cast<mz_uint>(index), data.data(),
                                      static_cast<std::size_t>(data.size()), 0))
        throw std::invalid_argument("Damaged archive entry");
    return data;
}
// Archive member keys are generated by the app; refuse anything that could escape or collide.
bool safeKey(const std::string& key) {
    static const QRegularExpression pattern(QStringLiteral("^[A-Za-z0-9_-]{1,64}$"));
    return pattern.match(QString::fromStdString(key)).hasMatch();
}
bool safeExtension(const std::string& ext) {
    static const QRegularExpression pattern(QStringLiteral("^[a-z0-9]{1,5}$"));
    return pattern.match(QString::fromStdString(ext)).hasMatch();
}
QString fontExtension(const std::string& fileName) {
    const auto dot = fileName.rfind('.');
    QString ext = dot == std::string::npos ? QStringLiteral("ttf")
                                           : QString::fromStdString(fileName.substr(dot + 1)).toLower();
    return safeExtension(ext.toStdString()) ? ext : QStringLiteral("ttf");
}
