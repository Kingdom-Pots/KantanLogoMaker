Result saveProject(const QString& path, Snapshot document, const RenderServices& services,
                   std::shared_ptr<MemoryBudget> budget) {
    if (!document)
        return {Status::InvalidData, "No document to save"};
    if (auto valid = validateDocument(*document); !valid)
        return valid;
    try {
        QSaveFile file(path);
        file.setDirectWriteFallback(false);
        if (!file.open(QIODevice::WriteOnly))
            return {Status::InvalidData, file.errorString().toStdString()};
        Archive archive(file, budget, true);
        if (!mz_zip_writer_init_v2(&archive.zip, 0, MZ_ZIP_FLAG_WRITE_ZIP64))
            throw std::runtime_error("Could not initialize archive");
        QJsonArray objects, images, fonts;
        for (const auto& o : document->objects)
            objects.append(objectToJson(*o));
        for (const auto& [key, image] : document->images) {
            if (!safeKey(key) || !image.encoded || !safeExtension(image.format))
                throw std::runtime_error("Image cannot be stored");
            const QString entry = QStringLiteral("images/%1.%2")
                                      .arg(QString::fromStdString(key), QString::fromStdString(image.format));
            archive.add(entry.toUtf8(), fromBytes(image.encoded),
                        image.format != "png" && image.format != "jpg");
            images.append(QJsonObject{{"key", QString::fromStdString(key)},
                                      {"entry", entry},
                                      {"source", QString::fromStdString(image.sourceName)},
                                      {"width", static_cast<double>(image.pixels->width)},
                                      {"height", static_cast<double>(image.pixels->height)}});
        }
        for (const auto& [key, font] : document->fonts) {
            if (!safeKey(key))
                throw std::runtime_error("Font cannot be stored");
            QJsonObject entry{{"key", QString::fromStdString(key)},
                              {"family", QString::fromStdString(font.family)},
                              {"file", QString::fromStdString(font.fileName)},
                              {"embed", font.embed}};
            if (font.embed && font.data) {
                const QString member = QStringLiteral("fonts/%1.%2")
                                           .arg(QString::fromStdString(key), fontExtension(font.fileName));
                archive.add(member.toUtf8(), fromBytes(font.data));
                entry["entry"] = member;
            }
            fonts.append(entry);
        }
        const QJsonObject manifest{{"format", "kantanlogo-experimental"},
                                   {"version", ProjectSchema},
                                   {"pixelFormat", "premultiplied-rgba8-srgb"},
                                   {"units", "artboard"},
                                   {"state", QString::number(document->state)},
                                   {"artboard", artboardToJson(document->artboard)},
                                   {"export", exportToJson(document->exportSettings)},
                                   {"palette", paletteToJson(document->palette)},
                                   {"objects", objects},
                                   {"images", images},
                                   {"fonts", fonts}};
        const auto bytes = QJsonDocument(manifest).toJson(QJsonDocument::Compact);
        if (bytes.size() > ManifestLimit)
            throw std::length_error("Manifest limit reached");
        archive.add("manifest.json", bytes);
        // Thumbnail: presentation only, never read back as document data.
        RenderRequest thumb;
        thumb.width = thumb.height = 256;
        thumb.toPixels =
            fitTransform({0, 0, document->artboard.width, document->artboard.height}, 256, 256, 0);
        thumb.exportSize = 256;
        archive.add("thumbnail.png", encodePng(render(*document, thumb, services, budget)), false);
        if (!mz_zip_writer_finalize_archive(&archive.zip))
            throw std::runtime_error("Could not finalize archive");
        if (!file.commit())
            return {Status::InvalidData, file.errorString().toStdString()};
        return {};
    } catch (const std::exception& e) {
        return {Status::InvalidData, e.what()};
    }
}
LoadResult loadProject(const QString& path, std::shared_ptr<MemoryBudget> budget) {
    try {
        QFile file(path);
        if (!file.open(QIODevice::ReadOnly))
            return {{Status::InvalidData, file.errorString().toStdString()}, {}, {}};
        if (file.size() < 22 || file.size() > ArchiveLimit)
            throw std::invalid_argument("Unsupported archive size");
        Archive archive(file, budget, false);
        if (!mz_zip_reader_init(&archive.zip, static_cast<mz_uint64>(file.size()), 0))
            throw std::invalid_argument("Not a valid Kantan LogoMaker project");
        const auto count = mz_zip_reader_get_num_files(&archive.zip);
        if (count > EntryLimit)
            throw std::length_error("Too many archive entries");
        QSet<QByteArray> names;
        std::uint64_t expanded{};
        for (mz_uint i = 0; i < count; ++i) {
            mz_zip_archive_file_stat s{};
            if (!mz_zip_reader_file_stat(&archive.zip, i, &s) || s.m_is_directory || s.m_is_encrypted ||
                s.m_uncomp_size > static_cast<mz_uint64>(MemberLimit))
                throw std::invalid_argument("Invalid archive member");
            QByteArray name(s.m_filename);
            if (names.contains(name))
                throw std::invalid_argument("Duplicate archive entry");
            names.insert(name);
            expanded += s.m_uncomp_size;
            if (expanded > budget->limit())
                throw std::length_error("Expanded archive exceeds memory budget");
        }
        QJsonParseError error;
        const auto json =
            QJsonDocument::fromJson(extract(archive, "manifest.json", ManifestLimit, budget), &error);
        if (error.error != QJsonParseError::NoError || !json.isObject())
            throw std::invalid_argument("Invalid manifest JSON");
        const auto root = json.object();
        if (root.value("format") != "kantanlogo-experimental")
            throw std::invalid_argument("Not a Kantan LogoMaker project");
        if (!root.value("version").isDouble() || root.value("version").toDouble() > ProjectSchema)
            throw std::invalid_argument("This project was saved by a newer version of Kantan LogoMaker");
        if (root.value("version").toDouble() != ProjectSchema ||
            root.value("pixelFormat") != "premultiplied-rgba8-srgb")
            throw std::invalid_argument("Unsupported project schema");
        DocumentData doc;
        doc.artboard = artboardFromJson(root.value("artboard").toObject());
        if (!root.value("artboard").isObject() || !root.value("export").isObject())
            throw std::invalid_argument("Missing artboard or export settings");
        doc.exportSettings = exportFromJson(root.value("export").toObject());
        if (root.contains("palette")) {
            if (!root.value("palette").isArray())
                throw std::invalid_argument("Invalid palette");
            doc.palette = paletteFromJson(root.value("palette").toArray());
        }
        QSet<QByteArray> referenced{"manifest.json"};
        if (names.contains("thumbnail.png"))
            referenced.insert("thumbnail.png");
        LoadResult out;
        if (!root.value("images").isArray() || !root.value("fonts").isArray() ||
            !root.value("objects").isArray())
            throw std::invalid_argument("Missing manifest sections");
        for (const auto v : root.value("images").toArray()) {
            const auto o = v.toObject();
            const auto key = o.value("key").toString().toStdString();
            const auto entry = o.value("entry").toString().toUtf8();
            if (!v.isObject() || !safeKey(key) || doc.images.contains(key) ||
                !entry.startsWith("images/" + QByteArray::fromStdString(key) + ".") ||
                referenced.contains(entry))
                throw std::invalid_argument("Invalid image reference");
            referenced.insert(entry);
            auto decoded = decodeImage(extract(archive, entry, MemberLimit, budget),
                                       o.value("source").toString(), budget);
            if (!decoded.result)
                throw std::invalid_argument("Embedded image could not be decoded: " + decoded.result.message);
            if (o.value("width").toDouble() != static_cast<double>(decoded.image.pixels->width) ||
                o.value("height").toDouble() != static_cast<double>(decoded.image.pixels->height))
                throw std::invalid_argument("Embedded image size does not match the manifest");
            doc.images[key] = std::move(decoded.image);
        }
        for (const auto v : root.value("fonts").toArray()) {
            const auto o = v.toObject();
            const auto key = o.value("key").toString().toStdString();
            if (!v.isObject() || !safeKey(key) || doc.fonts.contains(key) || !o.value("family").isString() ||
                !o.value("embed").isBool())
                throw std::invalid_argument("Invalid font reference");
            EmbeddedFont font{{},
                              o.value("family").toString().toStdString(),
                              o.value("file").toString().toStdString(),
                              o.value("embed").toBool()};
            if (o.contains("entry")) {
                const auto entry = o.value("entry").toString().toUtf8();
                if (!entry.startsWith("fonts/" + QByteArray::fromStdString(key) + ".") ||
                    referenced.contains(entry))
                    throw std::invalid_argument("Invalid font member");
                referenced.insert(entry);
                font.data = toBytes(extract(archive, entry, 64LL * 1024 * 1024, budget));
            } else if (font.embed)
                throw std::invalid_argument("Embedded font data is missing");
            doc.fonts[key] = std::move(font);
        }
        const auto objects = root.value("objects").toArray();
        if (objects.size() > static_cast<qsizetype>(MaxObjects))
            throw std::length_error("Too many objects");
        for (const auto v : objects) {
            if (!v.isObject())
                throw std::invalid_argument("Invalid object");
            doc.objects.push_back(std::make_shared<const Object>(objectFromJson(v.toObject())));
        }
        if (names != referenced)
            throw std::invalid_argument("Unreferenced archive entries");
        if (auto valid = validateDocument(doc); !valid)
            return {valid, {}, {}};
        out.result = {};
        out.document = std::make_shared<const DocumentData>(std::move(doc));
        return out;
    } catch (const std::exception& e) {
        return {{Status::InvalidData, e.what()}, {}, {}};
    }
}
